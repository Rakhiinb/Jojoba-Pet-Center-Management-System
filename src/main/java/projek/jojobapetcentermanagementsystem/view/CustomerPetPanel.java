    private void btnAddCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCustomerActionPerformed
        Customer c = readCustomerForm();
        if (c == null) {
            return;
        }
        if (customerRepo.save(c)) {
            info("Customer berhasil ditambahkan.");
            clearCustomerForm();
            loadCustomers();
        } else {
            error("Gagal menyimpan customer.");
        }
    }//GEN-LAST:event_btnAddCustomerActionPerformed

    private void btnUpdateCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateCustomerActionPerformed
        int id = selectedCustomerId();
        if (id < 0) {
            warn("Pilih customer yang akan diubah.");
            return;
        }
        Customer c = readCustomerForm();
        if (c == null) {
            return;
        }
        c.setId(id);
        if (customerRepo.update(c)) {
            info("Customer berhasil diubah.");
            loadCustomers();
        } else {
            error("Gagal mengubah customer.");
        }
    }//GEN-LAST:event_btnUpdateCustomerActionPerformed

    private void btnDeleteCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteCustomerActionPerformed
        int id = selectedCustomerId();
        if (id < 0) {
            warn("Pilih customer yang akan dihapus.");
            return;
        }
        if (!confirm("Hapus customer ini?")) {
            return;
        }
        if (customerRepo.delete(id)) {
            info("Customer berhasil dihapus.");
            clearCustomerForm();
            loadCustomers();
        } else {
            // delete() false karena FK RESTRICT (atau error DB)
            error("Customer tidak bisa dihapus karena masih memiliki hewan atau riwayat transaksi.");
        }
    }//GEN-LAST:event_btnDeleteCustomerActionPerformed

