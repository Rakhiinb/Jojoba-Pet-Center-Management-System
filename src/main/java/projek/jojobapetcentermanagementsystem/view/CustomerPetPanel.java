    private void initTables() {
        customerModel = createReadOnlyModel(new String[]{"ID", "Nama", "Telepon", "Alamat"});
        tblCustomer.setModel(customerModel);
        tblCustomer.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblCustomer.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && !loading) {
                onCustomerSelected();
            }
        });

        petModel = createReadOnlyModel(new String[]{"ID", "Nama", "Jenis", "Jenis Kelamin"});
        tblPet.setModel(petModel);
        tblPet.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblPet.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && !loading) {
                onPetSelected();
            }
        });
    }

    private void initCombos() {
        cmbSpecies.setModel(new DefaultComboBoxModel<>(
                new String[]{"Kucing", "Anjing", "Kelinci", "Burung", "Hamster"}));
        cmbSpecies.setEditable(true); // boleh ketik jenis lain
        cmbGender.setModel(new DefaultComboBoxModel<>(new String[]{"Jantan", "Betina"}));
    }

    private DefaultTableModel createReadOnlyModel(String[] columns) {
        return new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

