    public void refresh() {
        loadCustomers();
    }

    // ---------------------------------------------------------------------
    // MUAT DATA
    // ---------------------------------------------------------------------
    private void loadCustomers() {
        int keepId = selectedCustomerId(); // ingat pilihan supaya tidak hilang saat refresh
        String keyword = txtSearch.getText().trim();
        List<Customer> data = keyword.isEmpty()
                ? customerRepo.findAll()
                : customerRepo.search(keyword);

        loading = true;
        customerModel.setRowCount(0);
        for (Customer c : data) {
            customerModel.addRow(new Object[]{c.getId(), c.getName(), c.getPhone(), c.getAddress()});
        }
        loading = false;

        reselectCustomer(keepId);
    }

    private void reselectCustomer(int id) {
        for (int i = 0; i < customerModel.getRowCount(); i++) {
            if ((int) customerModel.getValueAt(i, 0) == id) {
                tblCustomer.setRowSelectionInterval(i, i); // memicu onCustomerSelected()
                return;
            }
        }
        tblCustomer.clearSelection();
        onCustomerSelected(); // tidak ada pilihan: kosongkan form dan tabel hewan
    }

    private void loadPets(int customerId) {
        loading = true;
        petModel.setRowCount(0);
        if (customerId > 0) {
            for (Pet p : petRepo.findByCustomer(customerId)) {
                petModel.addRow(new Object[]{p.getId(), p.getName(), p.getSpecies(), p.getGender()});
            }
        }
        loading = false;
        clearPetForm();
    }

    // ---------------------------------------------------------------------
    // SELEKSI TABEL
    // ---------------------------------------------------------------------
    private void onCustomerSelected() {
        int row = tblCustomer.getSelectedRow();
        if (row < 0) {
            clearCustomerForm();
            loadPets(-1);
            return;
        }
        txtCustName.setText(str(customerModel.getValueAt(row, 1)));
        txtCustPhone.setText(str(customerModel.getValueAt(row, 2)));
        txtCustAddress.setText(str(customerModel.getValueAt(row, 3)));
        loadPets((int) customerModel.getValueAt(row, 0));
    }

    private void onPetSelected() {
        int row = tblPet.getSelectedRow();
        if (row < 0) {
            return;
        }
        txtPetName.setText(str(petModel.getValueAt(row, 1)));
        cmbSpecies.setSelectedItem(str(petModel.getValueAt(row, 2)));
        cmbGender.setSelectedItem(str(petModel.getValueAt(row, 3)));
    }

    private int selectedCustomerId() {
        int row = tblCustomer.getSelectedRow();
        return row < 0 ? -1 : (int) customerModel.getValueAt(row, 0);
    }

    private int selectedPetId() {
        int row = tblPet.getSelectedRow();
        return row < 0 ? -1 : (int) petModel.getValueAt(row, 0);
    }

    // ---------------------------------------------------------------------
    // PEMBACA FORM
    // ---------------------------------------------------------------------
    private Customer readCustomerForm() {
        String name = txtCustName.getText().trim();
        String phone = txtCustPhone.getText().trim();
        if (name.isEmpty() || phone.isEmpty()) {
            warn("Nama dan telepon customer wajib diisi.");
            return null;
        }
        Customer c = new Customer();
        c.setName(name);
        c.setPhone(phone);
        c.setAddress(txtCustAddress.getText().trim());
        return c;
    }

    private Pet readPetForm(int customerId) {
        String name = txtPetName.getText().trim();
        Object speciesObj = cmbSpecies.getSelectedItem();
        String species = speciesObj == null ? "" : speciesObj.toString().trim();
        Object genderObj = cmbGender.getSelectedItem();
        String gender = genderObj == null ? "" : genderObj.toString();

        if (name.isEmpty() || species.isEmpty() || gender.isEmpty()) {
            warn("Nama, jenis, dan jenis kelamin hewan wajib diisi.");
            return null;
        }
        Pet p = new Pet();
        p.setCustomerId(customerId);
        p.setName(name);
        p.setSpecies(species);
        p.setGender(gender);
        return p;
    }

    // ---------------------------------------------------------------------
    // UTILITAS
