    private void btnAddPetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddPetActionPerformed
        int customerId = selectedCustomerId();
        if (customerId < 0) {
            warn("Pilih customer pemilik hewan terlebih dahulu.");
            return;
        }
        Pet p = readPetForm(customerId);
        if (p == null) {
            return;
        }
        if (petRepo.save(p)) {
            info("Hewan berhasil ditambahkan.");
            loadPets(customerId);
        } else {
            error("Gagal menyimpan hewan.");
        }
    }//GEN-LAST:event_btnAddPetActionPerformed

    private void btnUpdatePetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdatePetActionPerformed
        int customerId = selectedCustomerId();
        int petId = selectedPetId();
        if (customerId < 0 || petId < 0) {
            warn("Pilih hewan yang akan diubah.");
            return;
        }
        Pet p = readPetForm(customerId);
        if (p == null) {
            return;
        }
        p.setId(petId);
        if (petRepo.update(p)) {
            info("Hewan berhasil diubah.");
            loadPets(customerId);
        } else {
            error("Gagal mengubah hewan.");
        }
    }//GEN-LAST:event_btnUpdatePetActionPerformed

